/* v0.10A3: launch, vector mark and generated PWA/native icon receipts. */
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const assert=require('node:assert/strict'),ts=require('typescript');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const launch=read('src/components/LaunchExperience.tsx');
const app=read('src/App.tsx');
const css=read('src/components/launch-experience.css');
const vector=read('public/frame-one-icon.svg');
const script=read('scripts/render-brand-icons.py');
const packageJSON=JSON.parse(read('package.json'));
const manifest=JSON.parse(read('public/manifest.webmanifest'));
for(const f of ['src/components/LaunchExperience.tsx','src/App.tsx']){
  const node=ts.createSourceFile(f,read(f),ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
  assert.equal(node.parseDiagnostics.length,0,'valid React syntax for '+f);
}
assert(launch.includes("COLD_MS=4000"),'exact four-second cold launch');
assert(launch.includes("RETURN_MS=1200"),'shorter return after prolonged background');
assert(launch.includes("RETURN_AFTER_MS=45000"),'brief picker/background pauses are not interrupted');
assert(launch.includes("prefers-reduced-motion: reduce"),'respect motion preference');
assert(launch.includes("aria-hidden=\"true\""),'launch is decorative and not a screenreader trap');
assert(app.includes('<LaunchExperience />'),'mount before main content');
assert(app.includes('frame-one-icon.svg'),'in-app icon uses consistent brand');
assert(css.includes('pointer-events:none'),'no blocked native Back or learner taps');
assert(css.includes('launch-exit'),'title dissolves at end of sequence');
assert(css.includes('@media(prefers-reduced-motion:reduce)'),'no animation when user prefers less motion');
assert(vector.includes('<svg')&&vector.includes('FRAME')===false&&vector.includes('url(#gold)'),'original logo vector artwork');
assert(read('index.html').includes('frame-one-icon.svg'),'favicon uses vector icon');
assert(manifest.icons.some(x=>x.src==='./frame-one-icon.svg'),'vector available for modern PWA launchers');
assert(manifest.icons.some(x=>x.src==='./icon-512.png'),'Android compatible PWA PNG still provided');
assert(packageJSON.scripts.build.startsWith('python3 scripts/render-brand-icons.py --web &&'),'web build generates art before bundle');
for(const f of ['.github/workflows/android-debug.yml','.github/workflows/android-emulator-qa.yml','.github/workflows/android-backup-picker-qa.yml']){
  assert(read(f).includes('python3 scripts/render-brand-icons.py --android'),'native icon generated by '+f);
}
assert(script.includes('mipmap-anydpi-v26'),'Android 8+ adaptive icon resource');
assert(script.includes('ic_launcher_foreground.png'),'Android foreground art');
assert(script.includes('ic_launcher_round.png'),'legacy circular icon');
assert(script.includes('zlib'),'generator needs no external image package');
const output=cp.execFileSync('python3',['scripts/render-brand-icons.py','--web'],{
  cwd:root,encoding:'utf8',timeout:60000
});
assert.match(output,/icon-512.png/);
for(const size of [192,512]){
  const buffer=fs.readFileSync(path.join(root,'public','icon-'+size+'.png'));
  assert(buffer.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])),'valid PNG signature');
  assert.equal(buffer.readUInt32BE(16),size);
  assert.equal(buffer.readUInt32BE(20),size);
  assert(buffer.length>600,'branded PNG has meaningful image data');
}
console.log('PASS: 4s cinema title, reduced motion, nonblocking native UX, matching SVG/PWA/adaptive Android logos, real PNG generation.');