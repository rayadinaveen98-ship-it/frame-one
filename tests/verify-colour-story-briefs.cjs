/* v0.16A1: protect the optional, story-first Colour Lab extension. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const lab=read('src/components/labs/ColourLab.tsx');
const scene=read('src/components/labs/CinemaScene.tsx');
const brief=read('src/components/labs/ColourStoryBriefs.tsx');
const css=read('src/components/labs/colour-story-briefs.css');
const browser=read('scripts/browser-smoke.cjs');
const app=read('src/App.tsx');
assert(lab.includes("import { ColourStoryBriefs }"),'new director exercise is mounted within existing Colour Lab');
assert(lab.includes('<ColourStoryBriefs mode={mode} strength={strength}'),'brief watches live lab choices');
assert(lab.includes('setMode(nextMode)')&&lab.includes('setStrength(nextStrength)'),'brief updates real illustrated choices');
assert(brief.includes('<details>')&&!brief.includes('<details open'),'optional exercise must stay collapsed by default');
for(const id of ['morning','reunion','last-bus'])assert(brief.includes("id: '"+id+"'"),'story brief '+id);
for(const mode of ['neutral','warm','cool'])assert(brief.includes(mode+':'),'no universal mood verdict: '+mode);
assert(brief.includes('mode === \'neutral\''),'neutral mode never pretends to show an overlay');
assert(brief.includes('strength === 0'),'zero overlay has its own accurate interpretation');
assert(brief.includes('aria-pressed={active === item.id}'),'brief choices expose selection to assistive tech');
assert(brief.includes('data-colour-brief-starter')&&brief.includes('data-colour-brief-review'),'hands-on preset and interpretation actions');
assert(brief.includes('role="status" aria-live="polite"'),'feedback accessible');
assert(brief.includes('setReviewed(false)'),'new scene/preset hides obsolete discussion');
assert(brief.includes('session-only')&&brief.includes('no fake scoring'),'no new score or persistence');
assert(!/localStorage|fetch\(|navigator\.mediaDevices|AudioContext|Camera|permission/i.test(brief.replace(/camera/ig,'')),'story brief adds no storage, network or device permissions');
assert(scene.includes('Original storyboard image showing the same person at a bus stop'),'reuse genuine original image');
assert(css.includes('grid-template-columns:minmax(0,1fr)'),'mobile choices stack at small sizes');
assert(css.includes(':focus-visible'),'focus styles present');
assert(css.includes('prefers-reduced-motion'),'reduced motion respected');
assert(app.includes("const [colourMode,setColourMode]")&&app.includes("const [colourStrength,setColourStrength]") ,"lab state remains intact");
assert(browser.includes('colour-story-briefs')&&browser.includes('data-colour-brief-starter'),'compiled browser QA checks live scene handoff');
console.log('PASS: three story-first colour briefs, accessible interaction, original art, local session-only and mobile safety.');
